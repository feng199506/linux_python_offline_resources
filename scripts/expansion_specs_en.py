"""New Linux x86-64 CPU environment groups for the expansion pass."""
from __future__ import annotations

from prepare_offline_en import env_spec


def both(
    stem: str,
    title_cn: str,
    packages: list[str],
    imports: list[str],
    notes_cn: str,
    needs_torch_cpu: bool = False,
) -> list[dict]:
    out = []
    for py, suffix, extra_note in (
        ("3.10", "py310", ""),
        ("3.12", "py312", "CPython 3.12 对应组合。"),
    ):
        note = title_cn
        notes = notes_cn if py == "3.10" else f"{notes_cn} {extra_note}".strip()
        title = title_cn if py == "3.10" else f"{title_cn}（新 Python）"
        out.append(
            env_spec(
                f"{stem}_{suffix}",
                title,
                py,
                packages,
                imports,
                notes,
                needs_torch_cpu=needs_torch_cpu,
            )
        )
    return out


